// Compute standard Web Crypto Hashes
export async function computeHash(text, algorithm = 'SHA-256') {
  if (algorithm === 'MD5') {
    return md5(text);
  }
  const encoder = new TextEncoder();
  const data = encoder.encode(text);
  const hashBuffer = await crypto.subtle.digest(algorithm, data);
  return bufToHex(hashBuffer);
}

// Compute HMAC-SHA256
export async function computeHMAC(message, secret) {
  const enc = new TextEncoder();
  const key = await crypto.subtle.importKey(
    'raw',
    enc.encode(secret),
    { name: 'HMAC', hash: { name: 'SHA-256' } },
    false,
    ['sign']
  );
  const signature = await crypto.subtle.sign('HMAC', key, enc.encode(message));
  return bufToHex(signature);
}

// Generate UUID v4 (Random)
export function generateUUIDv4() {
  return crypto.randomUUID ? crypto.randomUUID() : 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, c => {
    const r = (Math.random() * 16) | 0;
    return (c === 'x' ? r : (r & 0x3) | 0x8).toString(16);
  });
}

// Generate UUID v7 (Time-Ordered)
export function generateUUIDv7() {
  const bytes = new Uint8Array(16);
  crypto.getRandomValues(bytes);
  const timestamp = BigInt(Date.now());

  // 48-bit timestamp
  bytes[0] = Number((timestamp >> 40n) & 0xffn);
  bytes[1] = Number((timestamp >> 32n) & 0xffn);
  bytes[2] = Number((timestamp >> 24n) & 0xffn);
  bytes[3] = Number((timestamp >> 16n) & 0xffn);
  bytes[4] = Number((timestamp >> 8n) & 0xffn);
  bytes[5] = Number(timestamp & 0xffn);

  // Version 7
  bytes[6] = (bytes[6] & 0x0f) | 0x70;
  // Variant RFC 4122
  bytes[8] = (bytes[8] & 0x3f) | 0x80;

  let hex = '';
  for (let i = 0; i < 16; i++) {
    hex += bytes[i].toString(16).padStart(2, '0');
    if (i === 3 || i === 5 || i === 7 || i === 9) hex += '-';
  }
  return hex;
}

// Secure Random Password Generator with Entropy
export function generatePassword(options = {}) {
  const {
    length = 16,
    uppercase = true,
    lowercase = true,
    numbers = true,
    symbols = true,
    excludeAmbiguous = false
  } = options;

  let lowerChars = 'abcdefghijklmnopqrstuvwxyz';
  let upperChars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
  let numberChars = '0123456789';
  let symbolChars = '!@#$%^&*()_+~`|}{[]:;?><,./-=';

  if (excludeAmbiguous) {
    // Exclude l, 1, I, o, 0, O, etc.
    lowerChars = lowerChars.replace(/[l1o]/g, '');
    upperChars = upperChars.replace(/[IO]/g, '');
    numberChars = numberChars.replace(/[01]/g, '');
  }

  let charset = '';
  if (lowercase) charset += lowerChars;
  if (uppercase) charset += upperChars;
  if (numbers) charset += numberChars;
  if (symbols) charset += symbolChars;

  if (!charset) charset = lowerChars;

  const array = new Uint32Array(length);
  crypto.getRandomValues(array);

  let password = '';
  for (let i = 0; i < length; i++) {
    password += charset[array[i] % charset.length];
  }

  // Calculate entropy in bits: E = L * log2(R)
  const poolSize = charset.length;
  const entropy = Math.round(length * Math.log2(poolSize));

  let strength = 'Weak';
  let badgeClass = 'badge-danger';
  if (entropy >= 80) {
    strength = 'Very Strong';
    badgeClass = 'badge-success';
  } else if (entropy >= 60) {
    strength = 'Strong';
    badgeClass = 'badge-success';
  } else if (entropy >= 45) {
    strength = 'Moderate';
    badgeClass = 'badge-warning';
  }

  return { password, entropy, strength, badgeClass, poolSize };
}
